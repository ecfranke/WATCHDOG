#!/usr/bin/env node
// Prints (and saves) the nginx config for putting the main server behind aaPanel / nginx.
//
//   npm run nginx                 uses PORT and PUBLIC_URL from .env
//   npm run nginx -- --port 9000  override the port
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import dotenv from "dotenv";

const APP_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The location blocks to paste inside the site's server { } block in aaPanel. */
export function buildNginx({ port, upstreamHost = "127.0.0.1", publicUrl = "" }) {
  const up = `http://${upstreamHost}:${port}`;
  const site = publicUrl ? ` for ${publicUrl}` : "";
  return `    # ---- Watchdog main server${site} -> ${up} ----
    # Generated by "npm run nginx". Paste inside the server { } block (aaPanel: Website → site → Config),
    # e.g. right after the "#SSL-END" line. Don't also add a Reverse proxy for this site in aaPanel.

    # Live dashboard updates (WebSocket)
    location /ws {
        proxy_pass ${up};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
    }

    # Everything else: dashboard, API, sub server reports
    location / {
        proxy_pass ${up};
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_read_timeout 60s;
        client_max_body_size 2m;
    }
    # ---- end Watchdog ----
`;
}

export function writeNginxFile(text) {
  const dir = path.join(APP_DIR, "nginx");
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, "watchdog.conf");
  fs.writeFileSync(file, text);
  return file;
}

// ---- CLI
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  dotenv.config({ path: process.env.WATCHDOG_ENV_FILE || path.join(APP_DIR, ".env"), quiet: true });
  const i = process.argv.indexOf("--port");
  const port = Number(i > 0 ? process.argv[i + 1] : process.env.PORT || 8080);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    console.error(`Invalid port: ${port}`);
    process.exit(1);
  }
  const text = buildNginx({ port, publicUrl: (process.env.PUBLIC_URL || "").trim() });
  const file = writeNginxFile(text);
  console.log(text);
  console.log(`Saved to ${path.relative(process.cwd(), file) || file}`);
}
